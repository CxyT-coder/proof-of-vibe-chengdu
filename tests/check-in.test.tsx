test("a Phantom-like wallet keeps the reviewed message and confirms only after explicit approval", async () => {
  surfnet.fundSol(mockWalletAddress, 2_000_000_000);
  const client = createAppClient("localnet", {
    rpcUrl: surfnet.rpcUrl,
    rpcSubscriptionsUrl: surfnet.wsUrl,
  });
  await waitFor(() =>
    expect(
      client.wallet
        .getState()
        .wallets.some((wallet) => wallet.name === "Mock Wallet")
    ).toBe(true)
  );
  const discovered = client.wallet
    .getState()
    .wallets.find((wallet) => wallet.name === "Mock Wallet")!;
  await client.wallet.connect(discovered);
  const originalSign =
    mockWallet.features["solana:signTransaction"].signTransaction;
  const sign = vi.spyOn(
    mockWallet.features["solana:signTransaction"],
    "signTransaction"
  );
  sign.mockImplementation(
    async (...inputs: readonly { transaction: Uint8Array }[]) =>
      originalSign(
        ...inputs.map(({ transaction }) => {
          const walletTransaction = applyPhantomPriorityFees(transaction);
          expect(walletTransaction).toEqual(transaction);
          return { transaction: walletTransaction };
        })
      )
  );
  const wrapper = ({ children }: { children: ReactNode }) => (
    <StrictMode>
      <ClientProvider client={client}>{children}</ClientProvider>
    </StrictMode>
  );
  const { result } = renderHook(() => useCheckIn(), { wrapper });
  await waitFor(() => expect(result.current.isLoading).toBe(false));
  expect(result.current.feedError).toBeNull();
  await act(async () => {
    await result.current.confirm();
  });
  expect(sign).not.toHaveBeenCalled();
  await act(async () => {
    await result.current.prepare("钱包同学", "先模拟，再亲自签名");
  });
  expect(result.current.status).toBe("ready");
  expect(result.current.simulationSummary).toContain("转账 0 SOL");
  expect(sign).not.toHaveBeenCalled();
  await act(async () => {
    await result.current.confirm();
  });
  expect(sign).toHaveBeenCalledTimes(1);
  expect(result.current.status).toBe("success");
  expect(result.current.lastSignature).not.toBeNull();
  expect(
    result.current.entries.some(
      (entry) => entry.signature === result.current.lastSignature
    )
  ).toBe(true);
  await act(async () => {
    await result.current.prepare("下一笔", "钱包拒绝签名");
  });
  expect(result.current.lastSignature).toBeNull();
  sign.mockRejectedValueOnce(new Error("User rejected signing"));
  await act(async () => {
    await result.current.confirm();
  });
  expect(result.current.status).toBe("error");
  expect(result.current.transactionError).toContain("取消了钱包签名");
  expect(result.current.lastSignature).toBeNull();
});

test("the old unsigned memo would be enhanced by Phantom, but the prepared message has explicit budgets", async () => {
  const signer = await generateKeyPairSigner();
  surfnet.fundSol(signer.address, 1_000_000_000);
  const { value: lifetime } = await rpc.getLatestBlockhash().send();
  const oldMessage = pipe(
    createTransactionMessage({ version: 0 }),
    (m) => setTransactionMessageFeePayerSigner(signer, m),
    (m) => setTransactionMessageLifetimeUsingBlockhash(lifetime, m),
    (m) =>
      appendTransactionMessageInstructions(
        buildCheckInInstructions(signer, "钱包兼容", "明确预算再签名"),
        m
      )
  );
  const oldBytes = new Uint8Array(
    getTransactionEncoder().encode(compileTransaction(oldMessage))
  );
  expect(applyPhantomPriorityFees(oldBytes)).not.toEqual(oldBytes);
  const prepared = await simulateCheckIn(
    rpc,
    signer,
    "钱包兼容",
    "明确预算再签名"
  );
  const newBytes = new Uint8Array(
    getTransactionEncoder().encode(prepared.transaction)
  );
  expect(applyPhantomPriorityFees(newBytes)).toEqual(newBytes);
  expect(
    getTransactionMessageComputeUnitPrice(prepared.transactionMessage)
  ).toBe(0n);
});

test("an unreported CU estimate prevents preparing a wallet transaction instead of guessing a budget", async () => {
  const signer = await generateKeyPairSigner();
  surfnet.fundSol(signer.address, 1_000_000_000);
  const originalSimulate = rpc.simulateTransaction;
  const simulate = vi.fn(
    (...args: Parameters<typeof rpc.simulateTransaction>) => {
      const pending = originalSimulate(...args);
      return {
        ...pending,
        send: async (...options: Parameters<typeof pending.send>) => {
          const result = await pending.send(...options);
          return {
            ...result,
            value: { ...result.value, unitsConsumed: undefined },
          };
        },
      };
    }
  );
  const incompleteRpc = overrideRpcMethods({ simulateTransaction: simulate });
  await expect(
    simulateCheckIn(incompleteRpc, signer, "缺少估计", "需要正常的节点数据")
  ).rejects.toThrow("无法估计本次交易所需的计算预算");
  expect(simulate).toHaveBeenCalledTimes(1);
});

test("the finalized budgeted message is simulated again and its exact message determines the fee", async () => {
  const signer = await generateKeyPairSigner();
  surfnet.fundSol(signer.address, 1_000_000_000);
  const simulate = vi.fn(rpc.simulateTransaction);
  const fee = vi.fn(rpc.getFeeForMessage);
  const observedRpc = overrideRpcMethods({
    simulateTransaction: simulate,
    getFeeForMessage: fee,
  });
  const prepared = await simulateCheckIn(
    observedRpc,
    signer,
    "预算审核",
    "只签最终模拟的内容"
  );
  expect(simulate).toHaveBeenCalledTimes(2);
  expect(simulate.mock.calls[1][0]).toBe(
    getBase64EncodedWireTransaction(prepared.transaction)
  );
  const probe = decodeWalletMessage(
    new Uint8Array(getBase64Encoder().encode(simulate.mock.calls[0][0]))
  );
  expect(getTransactionMessageComputeUnitLimit(probe)).toBe(1_400_000);
  expect(getTransactionMessageComputeUnitPrice(probe)).toBe(0n);
  expect(fee).toHaveBeenCalledTimes(1);
  const feeMessageBytes = getBase64Encoder().encode(fee.mock.calls[0][0]);
  expect(feeMessageBytes).toEqual(prepared.transaction.messageBytes);
});

