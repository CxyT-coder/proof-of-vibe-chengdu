// Kit RPC methods are generated by a Proxy rather than own properties.
function overrideRpcMethods(
  overrides: Partial<Record<keyof typeof rpc, unknown>>
) {
  return new Proxy(rpc, {
    get(target, property, receiver) {
      return Object.hasOwn(overrides, property)
        ? Reflect.get(overrides, property)
        : Reflect.get(target, property, receiver);
    },
  });
}

function decodeWalletMessage(wireBytes: Uint8Array) {
  const transaction = getTransactionDecoder().decode(wireBytes);
  const compiled = getCompiledTransactionMessageDecoder().decode(
    transaction.messageBytes
  );
  if (compiled.version !== 0) throw new Error("Expected a v0 transaction");
  return decompileTransactionMessage(compiled, {
    lastValidBlockHeight: 0n,
  });
}

// Model Phantom's documented auto-fee conditions at the wallet boundary:
// unsigned, no existing compute-budget settings, and still below 1232 bytes.
function applyPhantomPriorityFees(wireBytes: Uint8Array) {
  const transaction = getTransactionDecoder().decode(wireBytes);
  const message = decodeWalletMessage(wireBytes);
  if (
    Object.values(transaction.signatures).some((value) => value !== null) ||
    getTransactionMessageComputeUnitLimit(message) !== undefined ||
    getTransactionMessageComputeUnitPrice(message) !== undefined
  ) {
    return wireBytes;
  }
  const enhanced = pipe(
    message,
    (m) => setTransactionMessageComputeUnitLimit(50_000, m),
    (m) => setTransactionMessageComputeUnitPrice(1_000n, m),
    compileTransaction,
    (transaction) => new Uint8Array(getTransactionEncoder().encode(transaction))
  );
  return enhanced.length < 1232 ? enhanced : wireBytes;
}

